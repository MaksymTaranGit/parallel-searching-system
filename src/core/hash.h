#pragma once

#include <cstdint>
#include <string_view>

//пояснення використання цієї функції:
//оскільки в цій архітектурі хеш від слова потрібен двічі
//(щоб визначити, в який із шардів попаде слово і всередині самаого шарду визначити початковий індекс в масиві),
// то можна хеш порахувати 1 раз і використати різні його частини для визначення номеру шарду і слоту в масиві
// а використання різних його частин позбавляє від проблеми кореляції бітів (коли і шард і слот обирається через % - беруться однакові молодші біти)

inline std::uint64_t hash_string(std::string_view key) noexcept {
  std::uint64_t h = 14695981039346656037ULL;
  for (unsigned char c : key) {
    h ^= static_cast<std::uint64_t>(c);
    h *= 1099511628211ULL;
  }

  h ^= h >> 30;
  h *= 0xbf58476d1ce4e5b9ULL;
  h ^= h >> 27;
  h *= 0x94d049bb133111ebULL;
  h ^= h >> 31;

  return h;
}